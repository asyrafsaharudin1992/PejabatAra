import assert from 'node:assert/strict';
import { projectionCell, isProjectionCa, type ProjectionPerson } from '../src/lib/hrProjection';
const ca: ProjectionPerson = { id: 'a', name: 'Athirah', code: 'A', company: 'KJ', designation: 'CLINIC ASSISTANT', employmentType: 'Permanent', status: 'Active', joinDate: '2026-06-03', confirmDate: '2026-09-08', resignDate: null };
assert.equal(projectionCell(ca, '2026-05', {}), null);
assert.deepEqual(projectionCell(ca, '2026-06', {}), { status: 'probation', notes: ['Join 3/6'] });
assert.equal(projectionCell(ca, '2026-08', {})?.status, 'probation');
assert.deepEqual(projectionCell(ca, '2026-09', {}), { status: 'permanent', notes: ['Confirm 8/9'] });
assert.equal(projectionCell(ca, '2026-12', { a: 'probation' })?.status, 'permanent');
const leaving = { ...ca, status: 'Inactive', resignDate: '2026-10-02' };
assert.equal(projectionCell(leaving, '2026-09', {})?.status, 'permanent');
assert.deepEqual(projectionCell(leaving, '2026-10', {}), { status: 'resigned', notes: ['Last 2/10'] });
assert.equal(projectionCell(leaving, '2026-11', {}), null);
assert.equal(projectionCell({ ...leaving, resignDate: null }, '2026-09', {}), null);
const nadiatul = { ...ca, joinDate: '2026-11-03', confirmDate: null };
assert.equal(projectionCell(nadiatul, '2026-10', {}), null);
assert.equal(projectionCell(nadiatul, '2026-11', {})?.status, 'unknown');
assert.equal(projectionCell(nadiatul, '2026-12', { a: 'not-probation' })?.status, 'unknown');
assert.equal(projectionCell(nadiatul, '2027-12', { a: 'probation' })?.status, 'probation'); // Never invent a future confirmation.
assert.equal(projectionCell({ ...ca, employmentType: 'Contract' }, '2026-11', {})?.status, 'contract');
assert.equal(isProjectionCa(ca), true);
assert.equal(isProjectionCa({ ...ca, designation: 'CLINIC ASSISTANT OFFICER' }), false);
assert.equal(isProjectionCa({ ...ca, designation: 'DR RESIDENT' }), false);
console.log('HR projection: joining, confirmation, leaving, unknown dates, future probation and CA scope passed.');

const { applyProjectionRange, emptyProjectionPlan, validateProjectionPlan } = await import('../src/lib/hrProjection');
const { projectionRows, displayedCell } = await import('../src/HRProjectionDocument');
const range = applyProjectionRange(emptyProjectionPlan(), 'a', '2026-04-15', '2026-06-20', { status: 'contract', note: 'Transfer planned', company: 'SK' });
assert.deepEqual(Object.keys(range.cells), ['a:2026-04', 'a:2026-05', 'a:2026-06']);
assert.deepEqual(validateProjectionPlan(range, '2026', ['a']), range);
assert.throws(() => applyProjectionRange(range, 'a', '2026-06-20', '2026-04-15', { status: 'contract', note: '' }));
assert.throws(() => validateProjectionPlan({ rows: [], cells: { 'a:2026-03': range.cells['a:2026-04'] } }, '2026', ['a']));
const liveCa = { ...ca, joinDate: '2026-01-01', confirmDate: '2026-02-01' };
assert.equal(projectionRows([liveCa], range, ['2026-05'], 'KJ').length, 0);
const transferred = projectionRows([liveCa], range, ['2026-05'], 'SK');
assert.equal(transferred.length, 1);
assert.equal(displayedCell(transferred[0], '2026-04', range, {})?.notes.includes('From 15/4'), true);
assert.equal(displayedCell(transferred[0], '2026-06', range, {})?.notes.includes('Until 20/6'), true);
assert.equal(projectionRows([liveCa], range, ['2026-07'], 'KJ').length, 1);
const restricted = applyProjectionRange(emptyProjectionPlan(), 'a', '2026-04-15', '2026-06-20', { status: 'permanent', note: '', company: 'KJ' }, true);
assert.equal(Object.keys(restricted.cells).length, 12);
assert.equal(displayedCell({ id: liveCa.id, name: liveCa.name, code: liveCa.code, company: liveCa.company, person: liveCa }, '2026-07', restricted, {}), null);
console.log('Projection date ranges passed: exact date notes, branch transfer, bounded visibility and validation.');

const { shiftProjectionMonth, projectionMonths, projectionPlanForYear, mergeProjectionPlans } = await import('../src/lib/hrProjection');
assert.equal(shiftProjectionMonth('2026-12', 1), '2027-01');
const rolling = projectionMonths('2026-02', '2027-01');
assert.equal(rolling.length, 12); assert.equal(rolling[0], '2026-02'); assert.equal(rolling.at(-1), '2027-01');
const crossYear = applyProjectionRange(emptyProjectionPlan(), 'a', '2026-12-15', '2027-02-10', { status: 'contract', note: 'Renewal', company: 'SK' });
const y2026 = projectionPlanForYear(crossYear, '2026'), y2027 = projectionPlanForYear(crossYear, '2027');
assert.deepEqual(Object.keys(y2026.cells), ['a:2026-12']);
assert.deepEqual(Object.keys(y2027.cells), ['a:2027-01', 'a:2027-02']);
validateProjectionPlan(y2026, '2026', ['a']); validateProjectionPlan(y2027, '2027', ['a']);
assert.deepEqual(mergeProjectionPlans({ 2026: y2026, 2027: y2027 }), crossYear);
console.log('Rolling projection passed: 12-month rollover, cross-year ranges, split-year storage and lossless merge.');

const liveRow = { id: liveCa.id, name: liveCa.name, code: liveCa.code, company: liveCa.company, person: liveCa };
const resignedForecast = applyProjectionRange(emptyProjectionPlan(), liveCa.id, '2026-11-01', '2026-11-25', { status: 'resigned', note: '', company: 'KJ' });
assert.equal(displayedCell(liveRow, '2026-10', resignedForecast, {})?.status, 'permanent');
assert.equal(displayedCell(liveRow, '2026-11', resignedForecast, {})?.status, 'resigned');
assert.equal(displayedCell(liveRow, '2026-12', resignedForecast, {}), null);
assert.equal(displayedCell(liveRow, '2027-01', resignedForecast, {}), null);
const profileLeft = { ...liveRow, person: { ...liveCa, resignDate: '2026-11-25', status: 'Inactive' } };
assert.equal(displayedCell(profileLeft, '2026-12', applyProjectionRange(emptyProjectionPlan(), liveCa.id, '2026-12-01', '2026-12-31', { status: 'permanent', note: '' }), {}), null);
const oldFutureForecast = applyProjectionRange(emptyProjectionPlan(), liveCa.id, '2026-11-01', '2026-12-31', { status: 'permanent', note: '' });
assert.equal(applyProjectionRange(oldFutureForecast, liveCa.id, '2026-11-01', '2026-11-25', { status: 'resigned', note: '' }).cells['a:2026-12'], undefined);
console.log('Resignation passed: visible in last month, hidden in following months / year, profile departure wins over stale forecasts.');
